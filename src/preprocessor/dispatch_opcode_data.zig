const std = @import("std");
const opcode_mod = @import("../opcodes/opcode.zig");
const UnifiedOpcode = opcode_mod.UnifiedOpcode;

/// Generic functions for handling opcode data retrieval from the dispatch instruction stream.
/// These functions map opcodes to their expected metadata types and provide efficient
/// access patterns for the dispatch system.
///
/// NOTE: In untraced release builds the schedule items are untagged 8-byte unions, so this
/// working safely depends on the schedule builder always emitting, after each handler, exactly
/// the metadata layout declared here for that handler's opcode. Every opcode handler passes
/// its own opcode, so the layout is fixed at compile time and no runtime tag check remains.
/// Number of schedule items an instruction occupies: its handler plus its metadata.
pub fn itemCount(comptime opcode: UnifiedOpcode) usize {
    return switch (opcode) {
        .PC,
        .PUSH1,
        .PUSH2,
        .PUSH3,
        .PUSH4,
        .PUSH5,
        .PUSH6,
        .PUSH7,
        .PUSH8,
        .JUMPDEST,
        .BLOCK_BEGIN,
        .PUSH_ADD_INLINE,
        .PUSH_MUL_INLINE,
        .PUSH_DIV_INLINE,
        .PUSH_SUB_INLINE,
        .PUSH_AND_INLINE,
        .PUSH_OR_INLINE,
        .PUSH_XOR_INLINE,
        .PUSH_MLOAD_INLINE,
        .PUSH_MSTORE_INLINE,
        .PUSH_MSTORE8_INLINE,
        .PUSH_ADD_DUP1_INLINE,
        .PUSH_ADD_POINTER,
        .PUSH_MUL_POINTER,
        .PUSH_DIV_POINTER,
        .PUSH_SUB_POINTER,
        .PUSH_AND_POINTER,
        .PUSH_OR_POINTER,
        .PUSH_XOR_POINTER,
        .PUSH_MLOAD_POINTER,
        .PUSH_MSTORE_POINTER,
        .PUSH_MSTORE8_POINTER,
        .PUSH_ADD_DUP1_POINTER,
        => 2,
        // A static jump carries its target cursor and the target block's metadata.
        .JUMP_TO_STATIC_LOCATION => 3,
        // The conditional forms also carry the fall-through block's metadata.
        .JUMPI_TO_STATIC_LOCATION, .ISZERO_JUMPI => 4,
        .PUSH9, .PUSH10, .PUSH11, .PUSH12, .PUSH13, .PUSH14, .PUSH15, .PUSH16 => 3,
        .PUSH17, .PUSH18, .PUSH19, .PUSH20, .PUSH21, .PUSH22, .PUSH23, .PUSH24 => 4,
        .PUSH25, .PUSH26, .PUSH27, .PUSH28, .PUSH29, .PUSH30, .PUSH31, .PUSH32 => 5,
        .INVALID_JUMP_TARGET,
        .STOP,
        .ADD,
        .MUL,
        .SUB,
        .DIV,
        .SDIV,
        .MOD,
        .SMOD,
        .ADDMOD,
        .MULMOD,
        .EXP,
        .SIGNEXTEND,
        .LT,
        .GT,
        .SLT,
        .SGT,
        .EQ,
        .ISZERO,
        .AND,
        .OR,
        .XOR,
        .NOT,
        .BYTE,
        .SHL,
        .SHR,
        .SAR,
        .CLZ,
        .KECCAK256,
        .ADDRESS,
        .BALANCE,
        .ORIGIN,
        .CALLER,
        .CALLVALUE,
        .CALLDATALOAD,
        .CALLDATASIZE,
        .CALLDATACOPY,
        .CODESIZE,
        .CODECOPY,
        .GASPRICE,
        .EXTCODESIZE,
        .EXTCODECOPY,
        .RETURNDATASIZE,
        .RETURNDATACOPY,
        .EXTCODEHASH,
        .BLOCKHASH,
        .COINBASE,
        .TIMESTAMP,
        .NUMBER,
        .PREVRANDAO,
        .GASLIMIT,
        .CHAINID,
        .SELFBALANCE,
        .BASEFEE,
        .BLOBHASH,
        .BLOBBASEFEE,
        .POP,
        .MLOAD,
        .MSTORE,
        .MSTORE8,
        .SLOAD,
        .SSTORE,
        .JUMP,
        .JUMPI,
        .MSIZE,
        .GAS,
        .TLOAD,
        .TSTORE,
        .MCOPY,
        .PUSH0,
        .DUP1,
        .DUP2,
        .DUP3,
        .DUP4,
        .DUP5,
        .DUP6,
        .DUP7,
        .DUP8,
        .DUP9,
        .DUP10,
        .DUP11,
        .DUP12,
        .DUP13,
        .DUP14,
        .DUP15,
        .DUP16,
        .SWAP1,
        .SWAP2,
        .SWAP3,
        .SWAP4,
        .SWAP5,
        .SWAP6,
        .SWAP7,
        .SWAP8,
        .SWAP9,
        .SWAP10,
        .SWAP11,
        .SWAP12,
        .SWAP13,
        .SWAP14,
        .SWAP15,
        .SWAP16,
        .LOG0,
        .LOG1,
        .LOG2,
        .LOG3,
        .LOG4,
        .CREATE,
        .CALL,
        .CALLCODE,
        .RETURN,
        .DELEGATECALL,
        .CREATE2,
        .AUTH,
        .AUTHCALL,
        .STATICCALL,
        .REVERT,
        .INVALID,
        .SELFDESTRUCT,
