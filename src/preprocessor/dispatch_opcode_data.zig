/// The value `getOpData` returns for `opcode`: its typed metadata (if any) and the handler
/// and cursor of the instruction that follows it.
pub fn GetOpDataReturnType(
    comptime opcode: UnifiedOpcode,
    comptime OpcodeHandler: type,
    comptime Self: type,
    comptime Item: type,
) type {
    const PcMetadata = @FieldType(Item, "pc");
    const PushInlineMetadata = @FieldType(Item, "push_inline");
    const PushPointerMetadata = @FieldType(Item, "push_pointer");
    const JumpDestMetadata = @FieldType(Item, "jump_dest");
    const JumpStaticMetadata = @FieldType(Item, "jump_static");
    return switch (opcode) {
        .PC => struct { metadata: PcMetadata, next_handler: OpcodeHandler, next_cursor: Self },
        .PUSH1, .PUSH2, .PUSH3, .PUSH4, .PUSH5, .PUSH6, .PUSH7, .PUSH8 => struct { metadata: PushInlineMetadata, next_handler: OpcodeHandler, next_cursor: Self },
        // PUSH9-PUSH32: `limbs` points at 2, 3 or 4 inline 64-bit limbs, least significant first.
        .PUSH9,
        .PUSH10,
        .PUSH11,
        .PUSH12,
        .PUSH13,
        .PUSH14,
        .PUSH15,
        .PUSH16,
        .PUSH17,
        .PUSH18,
        .PUSH19,
        .PUSH20,
        .PUSH21,
        .PUSH22,
        .PUSH23,
        .PUSH24,
        .PUSH25,
        .PUSH26,
        .PUSH27,
        .PUSH28,
        .PUSH29,
        .PUSH30,
        .PUSH31,
        .PUSH32,
        => struct { limbs: [*]const Item, next_handler: OpcodeHandler, next_cursor: Self },
        .JUMPDEST, .BLOCK_BEGIN => struct { metadata: JumpDestMetadata, next_handler: OpcodeHandler, next_cursor: Self },
        .PUSH_ADD_INLINE, .PUSH_MUL_INLINE, .PUSH_DIV_INLINE, .PUSH_SUB_INLINE, .PUSH_AND_INLINE, .PUSH_OR_INLINE, .PUSH_XOR_INLINE, .PUSH_MLOAD_INLINE, .PUSH_MSTORE_INLINE, .PUSH_MSTORE8_INLINE, .PUSH_ADD_DUP1_INLINE => struct { metadata: PushInlineMetadata, next_handler: OpcodeHandler, next_cursor: Self },
        .JUMP_TO_STATIC_LOCATION, .JUMPI_TO_STATIC_LOCATION, .ISZERO_JUMPI => struct { metadata: JumpStaticMetadata, next_handler: OpcodeHandler, next_cursor: Self },
        .PUSH_ADD_POINTER, .PUSH_MUL_POINTER, .PUSH_DIV_POINTER, .PUSH_SUB_POINTER, .PUSH_AND_POINTER, .PUSH_OR_POINTER, .PUSH_XOR_POINTER, .PUSH_MLOAD_POINTER, .PUSH_MSTORE_POINTER, .PUSH_MSTORE8_POINTER, .PUSH_ADD_DUP1_POINTER => struct { metadata: PushPointerMetadata, next_handler: OpcodeHandler, next_cursor: Self },
        // No metadata.
        .INVALID_JUMP_TARGET,
        .STOP,
        .ADD,
        .MUL,
        .SUB,
        .DIV,
        .SDIV,
        .MOD,
        .SMOD,
        .ADDMOD,
        .MULMOD,
        .EXP,
        .SIGNEXTEND,
        .LT,
        .GT,
        .SLT,
        .SGT,
        .EQ,
        .ISZERO,
        .AND,
        .OR,
        .XOR,
        .NOT,
        .BYTE,
        .SHL,
        .SHR,
        .SAR,
        .CLZ,
        .KECCAK256,
        .ADDRESS,
        .BALANCE,
        .ORIGIN,
        .CALLER,
        .CALLVALUE,
        .CALLDATALOAD,
        .CALLDATASIZE,
        .CALLDATACOPY,
        .CODESIZE,
        .CODECOPY,
        .GASPRICE,
        .EXTCODESIZE,
        .EXTCODECOPY,
        .RETURNDATASIZE,
        .RETURNDATACOPY,
        .EXTCODEHASH,
        .BLOCKHASH,
        .COINBASE,
        .TIMESTAMP,
        .NUMBER,
        .PREVRANDAO,
        .GASLIMIT,
        .CHAINID,
        .SELFBALANCE,
        .BASEFEE,
        .BLOBHASH,
        .BLOBBASEFEE,
        .POP,
        .MLOAD,
        .MSTORE,
        .MSTORE8,
        .SLOAD,
        .SSTORE,
        .JUMP,
        .JUMPI,
        .MSIZE,
        .GAS,
        .TLOAD,
        .TSTORE,
        .MCOPY,
        .PUSH0,
        .DUP1,
        .DUP2,
        .DUP3,
        .DUP4,
        .DUP5,
        .DUP6,
        .DUP7,
        .DUP8,
        .DUP9,
        .DUP10,
        .DUP11,
        .DUP12,
        .DUP13,
        .DUP14,
        .DUP15,
        .DUP16,
        .SWAP1,
        .SWAP2,
        .SWAP3,
        .SWAP4,
        .SWAP5,
        .SWAP6,
        .SWAP7,
        .SWAP8,
        .SWAP9,
        .SWAP10,
        .SWAP11,
        .SWAP12,
        .SWAP13,
        .SWAP14,
        .SWAP15,
        .SWAP16,
        .LOG0,
        .LOG1,
        .LOG2,
        .LOG3,
        .LOG4,
        .CREATE,
        .CALL,
        .CALLCODE,
        .RETURN,
        .DELEGATECALL,
        .CREATE2,
        .AUTH,
        .AUTHCALL,
        .STATICCALL,
        .REVERT,
        .INVALID,
        .SELFDESTRUCT,
        => struct { next_handler: OpcodeHandler, next_cursor: Self },
    };
}

/// Get opcode data including metadata and next dispatch position.
/// This is a comptime-optimized method for specific opcodes.
///
/// `cursor` points at the current opcode's handler. Its metadata, if any, starts at
/// `cursor[1]`. Returns the next handler to call and the cursor to pass to it.
pub inline fn getOpData(
    comptime opcode: UnifiedOpcode,
    comptime Self: type,
    comptime Item: type,
    cursor: [*]const Item,
) GetOpDataReturnType(opcode, @FieldType(Item, "opcode_handler"), Self, Item) {
    const count = comptime itemCount(opcode);
    return switch (opcode) {
        .PC => .{
            .metadata = cursor[1].pc,
            .next_handler = cursor[count].opcode_handler,
            .next_cursor = Self{ .cursor = cursor + count },
        },
        .PUSH1, .PUSH2, .PUSH3, .PUSH4, .PUSH5, .PUSH6, .PUSH7, .PUSH8 => .{
            .metadata = cursor[1].push_inline,
            .next_handler = cursor[count].opcode_handler,
            .next_cursor = Self{ .cursor = cursor + count },
        },
        .PUSH9,
        .PUSH10,
        .PUSH11,
        .PUSH12,
        .PUSH13,
        .PUSH14,
        .PUSH15,
        .PUSH16,
        .PUSH17,
        .PUSH18,
        .PUSH19,
        .PUSH20,
        .PUSH21,
        .PUSH22,
        .PUSH23,
        .PUSH24,
        .PUSH25,
        .PUSH26,
        .PUSH27,
        .PUSH28,
        .PUSH29,
        .PUSH30,
        .PUSH31,
        .PUSH32,
        => .{
            .limbs = cursor + 1,
            .next_handler = cursor[count].opcode_handler,
            .next_cursor = Self{ .cursor = cursor + count },
        },
        .JUMPDEST, .BLOCK_BEGIN => .{
            .metadata = cursor[1].jump_dest,
            .next_handler = cursor[count].opcode_handler,
            .next_cursor = Self{ .cursor = cursor + count },
        },
        .PUSH_ADD_INLINE, .PUSH_MUL_INLINE, .PUSH_DIV_INLINE, .PUSH_SUB_INLINE, .PUSH_AND_INLINE, .PUSH_OR_INLINE, .PUSH_XOR_INLINE, .PUSH_MLOAD_INLINE, .PUSH_MSTORE_INLINE, .PUSH_MSTORE8_INLINE, .PUSH_ADD_DUP1_INLINE => .{
            .metadata = cursor[1].push_inline,
            .next_handler = cursor[count].opcode_handler,
            .next_cursor = Self{ .cursor = cursor + count },
        },
        .JUMP_TO_STATIC_LOCATION, .JUMPI_TO_STATIC_LOCATION, .ISZERO_JUMPI => .{
            .metadata = cursor[1].jump_static,
            .next_handler = cursor[count].opcode_handler,
            .next_cursor = Self{ .cursor = cursor + count },
        },
        .PUSH_ADD_POINTER, .PUSH_MUL_POINTER, .PUSH_DIV_POINTER, .PUSH_SUB_POINTER, .PUSH_AND_POINTER, .PUSH_OR_POINTER, .PUSH_XOR_POINTER, .PUSH_MLOAD_POINTER, .PUSH_MSTORE_POINTER, .PUSH_MSTORE8_POINTER, .PUSH_ADD_DUP1_POINTER => .{
            .metadata = cursor[1].push_pointer,
            .next_handler = cursor[count].opcode_handler,
            .next_cursor = Self{ .cursor = cursor + count },
        },
        .INVALID_JUMP_TARGET,
        .STOP,
        .ADD,
        .MUL,
        .SUB,
        .DIV,
        .SDIV,
        .MOD,
        .SMOD,
        .ADDMOD,
        .MULMOD,
        .EXP,
        .SIGNEXTEND,
        .LT,
        .GT,
        .SLT,
        .SGT,
        .EQ,
        .ISZERO,
        .AND,
        .OR,
        .XOR,
        .NOT,
        .BYTE,
        .SHL,
        .SHR,
        .SAR,
        .CLZ,
        .KECCAK256,
        .ADDRESS,
        .BALANCE,
        .ORIGIN,
        .CALLER,
        .CALLVALUE,
        .CALLDATALOAD,
        .CALLDATASIZE,
        .CALLDATACOPY,
        .CODESIZE,
        .CODECOPY,
        .GASPRICE,
        .EXTCODESIZE,
        .EXTCODECOPY,
        .RETURNDATASIZE,
        .RETURNDATACOPY,
        .EXTCODEHASH,
        .BLOCKHASH,
        .COINBASE,
        .TIMESTAMP,
        .NUMBER,
        .PREVRANDAO,
        .GASLIMIT,
        .CHAINID,
        .SELFBALANCE,
        .BASEFEE,
        .BLOBHASH,
        .BLOBBASEFEE,
        .POP,
        .MLOAD,
        .MSTORE,
        .MSTORE8,
        .SLOAD,
        .SSTORE,
        .JUMP,
        .JUMPI,
        .MSIZE,
        .GAS,
        .TLOAD,
        .TSTORE,
        .MCOPY,
        .PUSH0,
        .DUP1,
        .DUP2,
        .DUP3,
        .DUP4,
        .DUP5,
        .DUP6,
        .DUP7,
        .DUP8,
        .DUP9,
        .DUP10,
        .DUP11,
        .DUP12,
        .DUP13,
        .DUP14,
        .DUP15,
        .DUP16,
        .SWAP1,
        .SWAP2,
        .SWAP3,
        .SWAP4,
        .SWAP5,
        .SWAP6,
        .SWAP7,
        .SWAP8,
        .SWAP9,
        .SWAP10,
        .SWAP11,
        .SWAP12,
        .SWAP13,
        .SWAP14,
        .SWAP15,
        .SWAP16,
        .LOG0,
        .LOG1,
        .LOG2,
        .LOG3,
        .LOG4,
        .CREATE,
        .CALL,
        .CALLCODE,
        .RETURN,
        .DELEGATECALL,
        .CREATE2,
        .AUTH,
        .AUTHCALL,
        .STATICCALL,
        .REVERT,
        .INVALID,
        .SELFDESTRUCT,
        => .{
            .next_handler = cursor[count].opcode_handler,
            .next_cursor = Self{ .cursor = cursor + count },
        },
    };
}

